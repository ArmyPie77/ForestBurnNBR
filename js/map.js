// Simple burn-severity legend (static colors)
const legend = L.control({ position: "bottomright" });
legend.onAdd = function () {
  const div = L.DomUtil.create("div", "legend");
  const items = [
    // Match the magenta/orange burn palette used in the tiles
    { color: "#3c1b4a", label: "Low" },
    { color: "#8c2d7c", label: "Moderate" },
    { color: "#e24a8c", label: "High" },
    { color: "#ff9c33", label: "Very high" }
  ];
  div.innerHTML = '<div class="legend-title">Burn Severity</div>' +
    items.map(i => `
      <div class="legend-row">
        <span class="legend-swatch" style="background:${i.color}"></span>
        <span class="legend-label">${i.label}</span>
      </div>
    `).join("");
  return div;
};
legend.addTo(map);

