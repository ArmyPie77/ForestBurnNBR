function extendBounds(union, b) {
  if (!union) return L.latLngBounds(b);
  return union.extend(b);
}

function createPresetLayer(tile, bounds) {
  if (tile.tileUrl) {
    const minZoom = tile.minZoom ?? PRESET_TILE_DEFAULT_ZOOM.min;
    const maxZoom = tile.maxZoom ?? PRESET_TILE_DEFAULT_ZOOM.max;
    return L.tileLayer(tile.tileUrl, {
      opacity: PRESET_OVERLAY_OPACITY,
      bounds,
      minZoom,
      maxZoom,
      maxNativeZoom: maxZoom,
      tms: !!tile.tms,
      crossOrigin: true
    });
  }

  if (!tile.url) {
    console.warn("Tile is missing a url/tileUrl", tile);
    return null;
  }

  return L.imageOverlay(tile.url, bounds, { opacity: PRESET_OVERLAY_OPACITY });
}

function buildPresetTiles() {
  boundsUnion = null;
  PRESET_GROUPS.forEach(group => {
    const grpLayer = L.layerGroup();
    group.tiles.forEach(tile => {
      const bounds = L.latLngBounds(tile.bounds);
      const layer = createPresetLayer(tile, bounds);
      if (!layer) return;

      const rect = L.rectangle(bounds, {
        color: '#ffd166',
        weight: 1,
        fillOpacity: 0
      });

      rect.on('click', () => {
        showTileInfo(tile);
        highlightRect(rect);
      });

      layer.addTo(grpLayer);
      rect.addTo(grpLayer);
      presetRects.push(rect);
      boundsUnion = extendBounds(boundsUnion, bounds);
    });
    presetGroups.push({ name: group.name, layer: grpLayer });
  });

  if (boundsUnion) {
    map.fitBounds(boundsUnion.pad(0.1));
  }
}

